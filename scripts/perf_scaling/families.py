"""Structured adversarial input families for ftml scaling probes.

Each family maps n (a repetition count) to a wikitext string whose size is
roughly linear in n.  The driver measures render time across a ladder of n.
"""

R = lambda unit: (lambda n: unit * n)


def nest(open_, close, mid="x\n"):
    return lambda n: open_ * n + mid + close * n


def prefix(head, unit, tail=""):
    return lambda n: head + unit * n + tail


